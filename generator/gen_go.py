"""Go SDK generator (types + services). Core lives in go/client.go."""
from __future__ import annotations

import re
from pathlib import Path

HEADER = "// Code generated by generator/generate.py from openapi.json. DO NOT EDIT."

ACRONYMS = {"id": "ID", "url": "URL", "jid": "JID", "ids": "IDs", "ip": "IP", "ips": "IPs", "uri": "URI", "api": "API"}


def go_name(key: str) -> str:
    parts = re.split(r"[_\-\s]+|(?<=[a-z0-9])(?=[A-Z])", key)
    return "".join(ACRONYMS.get(p.lower(), p[:1].upper() + p[1:]) for p in parts if p)


def go_type(spec, s: dict | None, optional: bool) -> str:
    from generate import ref_name
    if not s:
        return "any"
    if "$ref" in s:
        t = spec.type_names[ref_name(s["$ref"])]
        return "*" + t if optional else t
    typ = s.get("type")
    if typ == "array":
        return "[]" + go_type(spec, s.get("items"), False)
    if typ == "object":
        return "map[string]any"
    if "enum" in s and all(isinstance(e, int) and not isinstance(e, bool) for e in s["enum"]):
        typ = "integer"
    if typ == "string" or ("enum" in s and typ not in ("integer", "number")):
        t = "string"
    elif typ == "integer":
        t = "int"
    elif typ == "number":
        t = "float64"
    elif typ == "boolean":
        t = "bool"
    else:
        return "any"
    # optional scalars are pointers so false/0 can be sent explicitly
    if optional and t in ("bool", "int", "float64"):
        return "*" + t
    if s.get("nullable") and t == "string":
        return "*string"
    return t


def comment(s: dict, indent: str) -> str:
    d = (s.get("description") or "").strip()
    if not d:
        return ""
    return "".join(f"{indent}// {l}\n" for l in d.splitlines())


def gen_go(spec, root: Path) -> None:
    from generate import RESOURCES, message_response, ref_name

    out = root / "go"
    t = f"{HEADER}\n\npackage zapz\n\n"
    for name, s in spec.schemas.items():
        tn = spec.type_names[name]
        props = s.get("properties") or {}
        t += comment(s, "")
        if not props:
            t += f"type {tn} map[string]any\n\n"
            continue
        req = set(s.get("required") or [])
        t += f"type {tn} struct {{\n"
        for k, v in props.items():
            opt = k not in req
            t += comment(v, "\t")
            omit = ",omitempty" if opt else ""
            t += f"\t{go_name(k)} {go_type(spec, v, opt)} `json:\"{k}{omit}\"`\n"
        t += "}\n\n"
    (out / "types_gen.go").write_text(t.rstrip() + "\n")

    r = f"{HEADER}\n\npackage zapz\n\nimport (\n\t\"context\"\n\t\"net/url\"\n)\n\nvar _ = url.PathEscape\n"
    for tag, prop in RESOURCES.items():
        svc = f"{tag}Service"
        r += f"\n// {svc} groups the {tag} endpoints.\ntype {svc} struct{{ c *Client }}\n"
        for op in [o for o in spec.ops if o["tag"] == tag]:
            name = op["name"][:1].upper() + op["name"][1:]
            args = ["ctx context.Context"] + [f"{p['arg']} string" for p in op["path_params"]]
            body = spec.body(op)
            body_t = None
            if op["body_schema"]:
                body_t = spec.type_names[op["body_schema"]]
            elif op["body_inline"] is not None:
                body_t = "map[string]any"
            if body_t:
                args.append(f"params {body_t}")
            qtype = None
            if op["query"]:
                qtype = f"{name}{tag}Query" if name in ("List", "Get") else f"{name}Query"
                args.append(f"query *{qtype}")
            mr = message_response(op["id"])
            resp = op["response"]
            if mr == "one":
                ret, zero, decl = "*Message", "nil", "out := new(Message)"
            elif mr == "many":
                ret, zero, decl = "[]Message", "nil", "var out []Message"
            elif resp and "$ref" in resp:
                tn = spec.type_names[ref_name(resp["$ref"])]
                ret, zero, decl = f"*{tn}", "nil", f"out := new({tn})"
            elif resp and resp.get("type") == "array" and "$ref" in resp.get("items", {}):
                tn = spec.type_names[ref_name(resp["items"]["$ref"])]
                ret, zero, decl = f"[]{tn}", "nil", f"var out []{tn}"
            elif resp and resp.get("type") == "object":
                ret, zero, decl = "map[string]any", "nil", "var out map[string]any"
            elif resp and resp.get("type") == "array" and (resp.get("items") or {}).get("type") == "object":
                ret, zero, decl = "[]map[string]any", "nil", "var out []map[string]any"
            else:
                ret, zero, decl = "any", "nil", "var out any"
            parts = []
            for i, chunk in enumerate(re.split(r"{(\w+)}", op["path"])):
                if i % 2:
                    arg = next(p["arg"] for p in op["path_params"] if p["name"] == chunk)
                    parts.append(f"url.PathEscape({arg})")
                elif chunk:
                    parts.append(f'"{chunk}"')
            path = " + ".join(parts)
            r += f"\n// {name}: {op['summary']} ({op['method']} /v1{op['path']}).\n"
            r += f"func (s *{svc}) {name}({', '.join(args)}) ({ret}, error) {{\n"
            if spec.auto_client_message_id(op) and op["body_schema"]:
                r += "\tif params.ClientMessageID == \"\" {\n\t\tparams.ClientMessageID = newID()\n\t}\n"
            q = "nil"
            if qtype:
                r += "\tvar q url.Values\n\tif query != nil {\n\t\tq = query.values()\n\t}\n"
                q = "q"
            b = "params" if body_t else "nil"
            if ret == "any":
                r += f"\t{decl}\n\terr := s.c.do(ctx, \"{op['method']}\", {path}, {q}, {b}, &out)\n\treturn out, err\n}}\n"
            elif ret.startswith("[]") or ret.startswith("map["):
                r += f"\t{decl}\n\tif err := s.c.do(ctx, \"{op['method']}\", {path}, {q}, {b}, &out); err != nil {{\n\t\treturn {zero}, err\n\t}}\n\treturn out, nil\n}}\n"
            else:
                r += f"\t{decl}\n\tif err := s.c.do(ctx, \"{op['method']}\", {path}, {q}, {b}, out); err != nil {{\n\t\treturn {zero}, err\n\t}}\n\treturn out, nil\n}}\n"
            if qtype:
                r += f"\n// {qtype} holds the optional query parameters of {name}.\ntype {qtype} struct {{\n"
                for qq in op["query"]:
                    gt = go_type(spec, qq["schema"], True)
                    r += f"\t{go_name(qq['name'])} {gt}\n"
                r += "}\n\n"
                r += f"func (q *{qtype}) values() url.Values {{\n\tv := url.Values{{}}\n"
                for qq in op["query"]:
                    fn = go_name(qq["name"])
                    gt = go_type(spec, qq["schema"], True)
                    if gt == "string":
                        r += f"\tif q.{fn} != \"\" {{\n\t\tv.Set(\"{qq['name']}\", q.{fn})\n\t}}\n"
                    else:
                        r += f"\tif q.{fn} != nil {{\n\t\tv.Set(\"{qq['name']}\", fmtAny(*q.{fn}))\n\t}}\n"
                r += "\treturn v\n}\n"
    (out / "services_gen.go").write_text(r)
    import shutil, subprocess
    if shutil.which("gofmt"):
        subprocess.run(["gofmt", "-w", str(out / "types_gen.go"), str(out / "services_gen.go")], check=False)


def go_query_type(op, tag: str) -> str:
    name = op["name"][:1].upper() + op["name"][1:]
    return f"{name}{tag}Query" if name in ("List", "Get") else f"{name}Query"


def go_docs_info(spec) -> dict:
    """Types and field names the docs need to render Go literals."""
    from generate import ref_name
    types = {}
    for name, s in spec.schemas.items():
        req = set(s.get("required") or [])
        fields = {}
        for k, v in (s.get("properties") or {}).items():
            opt = k not in req
            t = go_type(spec, v, opt)
            item = None
            if v.get("type") == "array" and "$ref" in (v.get("items") or {}):
                item = spec.type_names[ref_name(v["items"]["$ref"])]
            ref = spec.type_names[ref_name(v["$ref"])] if "$ref" in v else None
            fields[k] = {"name": go_name(k), "type": t, **({"item": item} if item else {}), **({"ref": ref} if ref else {})}
        types[spec.type_names[name]] = fields
    return types
