"""Java, C# and Ruby generators. Requests and responses are maps/dictionaries/hashes;
each method documents the body fields (from the DTOs) in its doc comment."""
from __future__ import annotations

import re
from pathlib import Path


def field_lines(spec, op) -> list[str]:
    """'to (string, required): ...' lines for doc comments."""
    from generate import ref_name
    body = spec.body(op)
    if not body:
        return []
    req = set(body.get("required") or [])
    out = []
    for k, v in (body.get("properties") or {}).items():
        if "$ref" in v:
            t = ref_name(v["$ref"]).removesuffix("Dto")
        elif v.get("type") == "array":
            it = v.get("items") or {}
            t = "list of " + (ref_name(it["$ref"]).removesuffix("Dto") if "$ref" in it else it.get("type", "any"))
        elif "enum" in v:
            t = " | ".join(str(e) for e in v["enum"])
        else:
            t = v.get("type", "any")
        desc = (v.get("description") or "").strip().splitlines()
        out.append(f"{k} ({t}{', required' if k in req else ''}){': ' + desc[0] if desc else ''}")
    return out


def path_parts(op, fmt_param):
    parts = []
    for i, chunk in enumerate(re.split(r"{(\w+)}", op["path"])):
        if i % 2:
            arg = next(p["arg"] for p in op["path_params"] if p["name"] == chunk)
            parts.append(fmt_param(arg))
        elif chunk:
            parts.append(f'"{chunk}"')
    return parts


def returns_list(spec, op) -> bool:
    from generate import message_response
    if message_response(op["id"]) == "many":
        return True
    r = op["response"] or {}
    return r.get("type") == "array"


def returns_object(spec, op) -> bool:
    from generate import message_response
    if message_response(op["id"]) == "one":
        return True
    r = op["response"] or {}
    return r.get("type") == "object" or "$ref" in r


# ------------------------------------------------------------------ Java

def gen_java(spec, root: Path) -> None:
    from generate import RESOURCES
    out = root / "java" / "src" / "main" / "java" / "com" / "zapz"
    out.mkdir(parents=True, exist_ok=True)
    for tag, prop in RESOURCES.items():
        cls = f"{tag}Resource"
        c = f"// Generated by generator/generate.py from openapi.json. Do not edit.\npackage com.zapz;\n\nimport java.util.List;\nimport java.util.Map;\n\n/** {tag}. */\npublic final class {cls} {{\n    private final ZapZ client;\n\n    {cls}(ZapZ client) {{\n        this.client = client;\n    }}\n"
        for op in [o for o in spec.ops if o["tag"] == tag]:
            args = [f"String {p['arg']}" for p in op["path_params"]]
            has_body = spec.body(op) is not None
            if has_body:
                args.append("Map<String, Object> params")
            if op["query"]:
                args.append("Map<String, Object> query")
            if returns_list(spec, op):
                ret, cast = "List<Object>", "(List<Object>) "
            elif returns_object(spec, op):
                ret, cast = "Map<String, Object>", "(Map<String, Object>) "
            else:
                ret, cast = "Object", ""
            path = " + ".join(path_parts(op, lambda a: f"ZapZ.encode({a})"))
            doc = [f"{op['summary']} ({op['method']} /v1{op['path']})."]
            fl = field_lines(spec, op)
            if fl:
                doc.append("<p>Body fields:</p><ul>" + "".join(f"<li>{l.replace('<', '&lt;')}</li>" for l in fl) + "</ul>")
            if op["query"]:
                doc.append("<p>Query: " + ", ".join(q["name"] for q in op["query"]) + "</p>")
            c += "\n    /**\n" + "".join(f"     * {l}\n" for l in doc) + "     */\n"
            if cast:
                c += "    @SuppressWarnings(\"unchecked\")\n"
            c += f"    public {ret} {op['name']}({', '.join(args)}) {{\n"
            call = f"client.request(\"{op['method']}\", {path}, {'params' if has_body else 'null'}, {'query' if op['query'] else 'null'}, {'true' if spec.auto_client_message_id(op) else 'false'})"
            c += f"        return {cast}{call};\n    }}\n"
            # convenience overloads without optional trailing maps
            if op["query"]:
                short = [a for a in args if not a.endswith(" query")]
                names = [a.split(" ")[-1] for a in short] + ["null"]
                c += f"\n    public {ret} {op['name']}({', '.join(short)}) {{\n        return {op['name']}({', '.join(names)});\n    }}\n"
            elif has_body and not spec.body_has_required(op):
                short = [a for a in args if not a.endswith(" params")]
                names = [a.split(" ")[-1] for a in short] + ["null"]
                c += f"\n    public {ret} {op['name']}({', '.join(short)}) {{\n        return {op['name']}({', '.join(names)});\n    }}\n"
        c += "}\n"
        (out / f"{cls}.java").write_text(c)


# ------------------------------------------------------------------ C#

def cs_name(n: str) -> str:
    return n[:1].upper() + n[1:]


def gen_csharp(spec, root: Path) -> None:
    from generate import RESOURCES
    out = root / "csharp" / "src" / "ZapZ" / "Resources"
    out.mkdir(parents=True, exist_ok=True)
    for tag, prop in RESOURCES.items():
        cls = f"{tag}Resource"
        c = f"// Generated by generator/generate.py from openapi.json. Do not edit.\n#nullable enable\nusing System.Collections.Generic;\nusing System.Text.Json;\nusing System.Threading;\nusing System.Threading.Tasks;\n\nnamespace ZapZ;\n\n/// <summary>{tag}.</summary>\npublic sealed class {cls}\n{{\n    private readonly ZapZClient _client;\n\n    internal {cls}(ZapZClient client) => _client = client;\n"
        for op in [o for o in spec.ops if o["tag"] == tag]:
            args = [f"string {p['arg']}" for p in op["path_params"]]
            has_body = spec.body(op) is not None
            if has_body:
                args.append("object body" if spec.body_has_required(op) else "object? body = null")
            if op["query"]:
                args.append("IDictionary<string, object?>? query = null")
            args.append("CancellationToken cancellationToken = default")
            path = " + ".join(path_parts(op, lambda a: f"ZapZClient.Encode({a})"))
            name = cs_name(op["name"]) + "Async"
            fl = field_lines(spec, op)
            c += f"\n    /// <summary>{op['summary']} ({op['method']} /v1{op['path']}).</summary>\n"
            if fl:
                c += "    /// <remarks>Body fields (anonymous object or dictionary):<list type=\"bullet\">" + "".join(f"<item>{l.replace('&', '&amp;').replace('<', '&lt;')}</item>" for l in fl) + "</list></remarks>\n"
            c += f"    public Task<JsonElement> {name}({', '.join(args)})\n"
            c += f"        => _client.RequestAsync(\"{op['method']}\", {path}, {'body' if has_body else 'null'}, {'query' if op['query'] else 'null'}, {'true' if spec.auto_client_message_id(op) else 'false'}, cancellationToken);\n"
        c += "}\n"
        (out / f"{cls}.cs").write_text(c)


# ------------------------------------------------------------------ Ruby

def gen_ruby(spec, root: Path) -> None:
    from generate import RESOURCES, snake
    out = root / "ruby" / "lib" / "zapz" / "resources"
    out.mkdir(parents=True, exist_ok=True)
    requires = []
    for tag, prop in RESOURCES.items():
        cls = f"{tag}Resource"
        fname = snake(tag) + "_resource"
        requires.append(fname)
        c = f"# frozen_string_literal: true\n\n# Generated by generator/generate.py from openapi.json. Do not edit.\n\nmodule ZapZ\n  # {tag}\n  class {cls}\n    def initialize(client)\n      @client = client\n    end\n"
        for op in [o for o in spec.ops if o["tag"] == tag]:
            args = [snake(p["arg"]) for p in op["path_params"]]
            has_body = spec.body(op) is not None
            if has_body:
                args.append("params" if spec.body_has_required(op) else "params = {}")
            for q in op["query"]:
                args.append(f"{snake(q['name'])}: nil")
            parts = []
            for i, chunk in enumerate(re.split(r"{(\w+)}", op["path"])):
                if i % 2:
                    arg = next(p["arg"] for p in op["path_params"] if p["name"] == chunk)
                    parts.append("#{ZapZ.escape(" + snake(arg) + ")}")
                else:
                    parts.append(chunk)
            path = '"' + "".join(parts) + '"'
            fl = field_lines(spec, op)
            c += f"\n    # {op['summary']} (+{op['method']} /v1{op['path']}+).\n"
            for l in fl:
                c += f"    # - {l}\n"
            q = "{" + ", ".join(f"{q['name']}: {snake(q['name'])}" for q in op["query"]) + "}" if op["query"] else "nil"
            c += f"    def {snake(op['name'])}({', '.join(args)})\n"
            c += f"      @client.request(:{op['method'].lower()}, {path}, body: {'params' if has_body else 'nil'}, query: {q}, auto_client_message_id: {'true' if spec.auto_client_message_id(op) else 'false'})\n    end\n"
        c += "  end\nend\n"
        (out / f"{fname}.rb").write_text(c)
    (root / "ruby" / "lib" / "zapz" / "resources.rb").write_text(
        "# frozen_string_literal: true\n\n# Generated by generator/generate.py. Do not edit.\n" + "".join(f"require_relative \"resources/{r}\"\n" for r in requires)
    )
