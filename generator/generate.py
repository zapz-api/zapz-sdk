def ts_type(spec: Spec, s: dict | None) -> str:
    if not s:
        return "unknown"
    if "$ref" in s:
        return spec.type_names[ref_name(s["$ref"])]
    if "enum" in s:
        t = " | ".join(json.dumps(v) for v in s["enum"])
    elif s.get("type") == "array":
        inner = ts_type(spec, s.get("items"))
        t = f"Array<{inner}>"
    elif s.get("type") == "object":
        if s.get("properties"):
            t = ts_inline_object(spec, s)
        else:
            t = "Record<string, any>"
    elif s.get("type") in ("integer", "number"):
        t = "number"
    elif s.get("type") == "boolean":
        t = "boolean"
    elif s.get("type") == "string":
        t = "string"
    else:
        t = "unknown"
    if s.get("nullable"):
        t += " | null"
    return t


def ts_doc(s: dict, indent: str) -> str:
    desc = (s.get("description") or "").strip()
    if not desc:
        return ""
    lines = desc.replace("*/", "* /").splitlines()
    if len(lines) == 1:
        return f"{indent}/** {lines[0]} */\n"
    return f"{indent}/**\n" + "".join(f"{indent} * {l}\n" for l in lines) + f"{indent} */\n"


def ts_inline_object(spec: Spec, s: dict, indent: str = "  ") -> str:
    req = set(s.get("required") or [])
    out = "{\n"
    for k, v in (s.get("properties") or {}).items():
        out += ts_doc(v, indent + "  ")
        key = k if re.match(r"^[A-Za-z_$][\w$]*$", k) else json.dumps(k)
        out += f"{indent}  {key}{'' if k in req else '?'}: {ts_type(spec, v)};\n"
    return out + indent + "}"


def gen_ts(spec: Spec) -> None:
    out = ROOT / "node" / "src" / "generated"
    # types
    t = f"// {HEADER}\n\n"
    for name, s in spec.schemas.items():
        tn = spec.type_names[name]
        t += ts_doc(s, "")
        if s.get("type") == "object" or "properties" in s:
            req = set(s.get("required") or [])
            t += f"export interface {tn} {{\n"
            for k, v in (s.get("properties") or {}).items():
                t += ts_doc(v, "  ")
                key = k if re.match(r"^[A-Za-z_$][\w$]*$", k) else json.dumps(k)
                t += f"  {key}{'' if k in req else '?'}: {ts_type(spec, v)};\n"
            t += "}\n\n"
        else:
            t += f"export type {tn} = {ts_type(spec, s)};\n\n"
    (out / "types.ts").write_text(t)

    # resources
    used_types: set[str] = set()
    classes = ""
    for tag, prop in RESOURCES.items():
        ops = [o for o in spec.ops if o["tag"] == tag]
        cls = f"{tag}Resource"
        classes += f"\n/** {tag} */\nexport class {cls} {{\n  constructor(private readonly client: ZapZCore) {{}}\n"
        for op in ops:
            args = [f"{p['arg']}: string" for p in op["path_params"]]
            body_t = None
            if op["body_schema"]:
                body_t = spec.type_names[op["body_schema"]]
                used_types.add(body_t)
            elif op["body_inline"]:
                body_t = ts_type(spec, op["body_inline"])
            if body_t:
                opt = "" if spec.body_has_required(op) else "?"
                args.append(f"params{opt}: {body_t}")
            if op["query"]:
                qt = "{ " + "; ".join(f"{q['name']}{'' if q['required'] else '?'}: {ts_type(spec, q['schema'])}" for q in op["query"]) + " }"
                qopt = "" if any(q["required"] for q in op["query"]) else "?"
                args.append(f"query{qopt}: {qt}")
            args.append("options?: RequestOptions")
            resp_t = ts_type(spec, op["response"]) if op["response"] else "any"
            mr = message_response(op["id"])
            if mr:
                resp_t = "Message" if mr == "one" else "Message[]"
            elif op["response"] and "$ref" in (op["response"] or {}):
                used_types.add(resp_t)
            if op["response"] and op["response"].get("type") == "array" and "$ref" in op["response"].get("items", {}):
                used_types.add(spec.type_names[ref_name(op["response"]["items"]["$ref"])])
            path_expr = "`" + re.sub(r"{(\w+)}", lambda m: "${encodeURIComponent(" + next(p["arg"] for p in op["path_params"] if p["name"] == m.group(1)) + ")}", op["path"]) + "`"
            req = [f"method: '{op['method']}'", f"path: {path_expr}"]
            if body_t:
                req.append("body: params")
            if op["query"]:
                req.append("query")
            if spec.auto_client_message_id(op):
                req.append("autoClientMessageId: true")
            classes += f"\n  /** {op['summary']} (`{op['method']} /v1{op['path']}`) */\n"
            classes += f"  {op['name']}({', '.join(args)}): Promise<{resp_t}> {{\n"
            classes += f"    return this.client.request({{ {', '.join(req)} }}, options);\n  }}\n"
        classes += "}\n"
    head = f"// {HEADER}\n\nimport type {{ ZapZCore, RequestOptions }} from '../core';\nimport type {{ Message }} from '../models';\n"
    if used_types:
        head += "import type {\n" + "".join(f"  {n},\n" for n in sorted(used_types)) + "} from './types';\n"
    resources_list = "".join(f"  {prop}: {tag}Resource;\n" for tag, prop in RESOURCES.items())
    init = "".join(f"    {prop}: new {tag}Resource(client),\n" for tag, prop in RESOURCES.items())
    tail = f"\nexport interface Resources {{\n{resources_list}}}\n\nexport function createResources(client: ZapZCore): Resources {{\n  return {{\n{init}  }};\n}}\n"
    (out / "resources.ts").write_text(head + classes + tail)


# ----------------------------------------------------------------- Python

PY_KEYWORDS = {"from", "global", "import", "class", "def", "return", "lambda", "pass", "in", "is", "not", "and", "or", "with", "as", "if", "else", "for", "while", "try", "except", "raise", "yield", "del", "async", "await", "None", "True", "False"}


def py_type(spec: Spec, s: dict | None) -> str:
    if not s:
        return "Any"
    if "$ref" in s:
        return f'"{spec.type_names[ref_name(s["$ref"])]}"'
    if "enum" in s:
        t = "Literal[" + ", ".join(json.dumps(v) for v in s["enum"]) + "]"
    elif s.get("type") == "array":
        t = f"List[{py_type(spec, s.get('items'))}]"
    elif s.get("type") == "object":
        t = "Dict[str, Any]"
    elif s.get("type") == "integer":
        t = "int"
    elif s.get("type") == "number":
        t = "float"
    elif s.get("type") == "boolean":
        t = "bool"
    elif s.get("type") == "string":
        t = "str"
    else:
        t = "Any"
    if s.get("nullable"):
        t = f"Optional[{t}]"
    return t


def py_comment(s: dict, indent: str) -> str:
    desc = (s.get("description") or "").strip()
    if not desc:
        return ""
    return "".join(f"{indent}# {l}\n" for l in desc.splitlines())


def gen_py(spec: Spec) -> None:
    out = ROOT / "python" / "zapz" / "_generated"
    t = f"# {HEADER}\nfrom __future__ import annotations\n\nfrom typing import Any, Dict, List, Literal, Optional, TypedDict\n\n"
    for name, s in spec.schemas.items():
        tn = spec.type_names[name]
        props = s.get("properties") or {}
        if not (s.get("type") == "object" or props):
            t += f"{tn} = {py_type(spec, s).strip(chr(34))}\n\n"
            continue
        req = set(s.get("required") or [])
        bad = [k for k in props if k in PY_KEYWORDS or not re.match(r"^[A-Za-z_]\w*$", k)]
        if bad:
            # functional syntax for keys that are not valid identifiers
            fields = ", ".join(f"{json.dumps(k)}: {py_type(spec, v)}" for k, v in props.items())
            t += f"{tn} = TypedDict({json.dumps(tn)}, {{{fields}}}, total=False)\n\n"
            continue
        r = {k: v for k, v in props.items() if k in req}
        o = {k: v for k, v in props.items() if k not in req}
        if r:
            t += f"class _{tn}Required(TypedDict):\n"
            for k, v in r.items():
                t += py_comment(v, "    ") + f"    {k}: {py_type(spec, v)}\n"
            t += f"\n\nclass {tn}(_{tn}Required, total=False):\n"
        else:
            t += f"class {tn}(TypedDict, total=False):\n"
        doc = (s.get("description") or "").strip()
        if doc:
            t += f'    """{doc}"""\n'
        if not o and not doc:
            t += "    pass\n"
        for k, v in o.items():
            t += py_comment(v, "    ") + f"    {k}: {py_type(spec, v)}\n"
        t += "\n\n"
    (out / "types.py").write_text(t.rstrip() + "\n")

    r = f"# {HEADER}\nfrom __future__ import annotations\n\nfrom typing import TYPE_CHECKING, Any, Dict, List, Optional\nfrom urllib.parse import quote\n\nfrom .types import *  # noqa: F401,F403\n\nif TYPE_CHECKING:\n    from .._core import ZapZCore\n    from ..models import Message\n\n\ndef _q(v: str) -> str:\n    return quote(str(v), safe=\"\")\n"
    for tag, prop in RESOURCES.items():
        ops = [o for o in spec.ops if o["tag"] == tag]
        r += f"\n\nclass {tag}Resource:\n    \"\"\"{tag}\"\"\"\n\n    def __init__(self, client: \"ZapZCore\") -> None:\n        self._client = client\n"
        for op in ops:
            args = ["self"] + [f"{snake(p['arg'])}: str" for p in op["path_params"]]
            body_t = None
            if op["body_schema"]:
                body_t = f'"{spec.type_names[op["body_schema"]]}"'
            elif op["body_inline"]:
                body_t = "Dict[str, Any]"
            if body_t:
                if spec.body_has_required(op):
                    args.append(f"params: {body_t}")
                else:
                    args.append(f"params: Optional[{body_t}] = None")
            kw = []
            for q in op["query"]:
                kw.append(f"{snake(q['name'])}: Optional[{py_type(spec, q['schema'])}] = None")
            kw.append("timeout: Optional[float] = None")
            sig = ", ".join(args) + ", *, " + ", ".join(kw)
            resp_t = py_type(spec, op["response"]) if op["response"] else "Any"
            mr = message_response(op["id"])
            if mr:
                resp_t = '"Message"' if mr == "one" else 'List["Message"]'

            path_expr = 'f"' + re.sub(r"{(\w+)}", lambda m: "{_q(" + snake(next(p["arg"] for p in op["path_params"] if p["name"] == m.group(1))) + ")}", op["path"]) + '"'
            call = [f'"{op["method"]}"', path_expr]
            if body_t:
                call.append("body=params")
            if op["query"]:
                call.append("query={" + ", ".join(f'"{q["name"]}": {snake(q["name"])}' for q in op["query"]) + "}")
            if spec.auto_client_message_id(op):
                call.append("auto_client_message_id=True")
            call.append("timeout=timeout")
            r += f"\n    def {snake(op['name'])}({sig}) -> {resp_t}:\n"
            r += f'        """{op["summary"]} (``{op["method"]} /v1{op["path"]}``)."""\n'
            r += f"        return self._client.request({', '.join(call)})\n"
    (out / "resources.py").write_text(r)
    (out / "__init__.py").write_text(f"# {HEADER}\nfrom .resources import " + ", ".join(f"{t}Resource" for t in RESOURCES) + "\n")


# ----------------------------------------------------------------- PHP

def php_shape(spec: Spec, s: dict | None, depth: int = 0) -> str:
    if not s:
        return "mixed"
    if "$ref" in s:
        if depth > 3:
            return "array<string, mixed>"
        return php_shape(spec, spec.schemas[ref_name(s["$ref"])], depth + 1)
    if "enum" in s:
        t = "|".join(f"'{v}'" if isinstance(v, str) else json.dumps(v) for v in s["enum"])
    elif s.get("type") == "array":
        t = f"list<{php_shape(spec, s.get('items'), depth)}>"
    elif s.get("type") == "object" or s.get("properties"):
        props = s.get("properties") or {}
        if not props:
            t = "array<string, mixed>"
        else:
            req = set(s.get("required") or [])
            t = "array{" + ", ".join(f"{k}{'' if k in req else '?'}: {php_shape(spec, v, depth)}" for k, v in props.items()) + "}"
    elif s.get("type") == "integer":
        t = "int"
    elif s.get("type") == "number":
        t = "float"
    elif s.get("type") == "boolean":
        t = "bool"
    elif s.get("type") == "string":
        t = "string"
    else:
        t = "mixed"
    if s.get("nullable"):
        t = f"{t}|null"
    return t


def gen_php(spec: Spec) -> None:
    out = ROOT / "php" / "src" / "Resources"
    for tag, prop in RESOURCES.items():
        ops = [o for o in spec.ops if o["tag"] == tag]
        cls = f"{tag}Resource"
        c = f"<?php\n\n// {HEADER}\n\ndeclare(strict_types=1);\n\nnamespace ZapZ\\Resources;\n\nuse ZapZ\\HttpClient;\n\n/** {tag} */\nfinal class {cls}\n{{\n    public function __construct(private readonly HttpClient $client)\n    {{\n    }}\n"
        for op in ops:
            args = [f"string ${p['arg']}" for p in op["path_params"]]
            doc = [f"{op['summary']} (`{op['method']} /v1{op['path']}`)", ""]
            for p in op["path_params"]:
                doc.append(f"@param string ${p['arg']}")
            body = spec.body(op)
            if body is not None:
                shape = php_shape(spec, body)
                if spec.body_has_required(op):
                    args.append("array $params")
                else:
                    args.append("array $params = []")
                doc.append(f"@param {shape} $params")
            if op["query"]:
                args.append("array $query = []")
                doc.append("@param array{" + ", ".join(f"{q['name']}?: {php_shape(spec, q['schema'])}" for q in op["query"]) + "} $query")
            args.append("array $options = []")
            doc.append("@param array{timeout?: float} $options")
            doc.append("@return array<string, mixed>|list<mixed>")
            parts = []
            for i, chunk in enumerate(re.split(r"{(\w+)}", op["path"])):
                if i % 2:
                    arg = next(p["arg"] for p in op["path_params"] if p["name"] == chunk)
                    parts.append(f"rawurlencode(${arg})")
                elif chunk:
                    parts.append(f"'{chunk}'")
            path_expr = " . ".join(parts)
            call = [f"'{op['method']}'", path_expr]
            call.append("$params" if body is not None else "null")
            call.append("$query" if op["query"] else "[]")
            call.append("$options")
            call.append("true" if spec.auto_client_message_id(op) else "false")
            c += "\n    /**\n" + "".join(f"     * {l}".rstrip() + "\n" for l in doc) + "     */\n"
            c += f"    public function {op['name']}({', '.join(args)}): array\n    {{\n"
            c += f"        return $this->client->request({', '.join(call)});\n    }}\n"
        c += "}\n"
        (out / f"{cls}.php").write_text(c)


def gen_map(spec: Spec, targets: list[Path]) -> None:
    """endpoint -> SDK method, used by the docs to render SDK samples."""
    sys.path.insert(0, str(Path(__file__).parent))
    from gen_go import go_docs_info, go_name, go_query_type, go_type
    out = {}
    for op in spec.ops:
        key = op["method"] + " /v1" + re.sub(r"{\w+}", "{}", op["path"])
        out[key] = {
            "resource": op["resource"],
            "js": op["name"],
            "py": snake(op["name"]),
            "php": op["name"],
            "params": [p["arg"] for p in op["path_params"]],
            "body": spec.body(op) is not None,
            "bodyRequired": spec.body_has_required(op),
            "query": [q["name"] for q in op["query"]],
            "go": op["name"][:1].upper() + op["name"][1:],
            "goResource": op["tag"],
            "goBody": spec.type_names[op["body_schema"]] if op["body_schema"] else ("map" if op["body_inline"] is not None else None),
            "goQuery": {"type": go_query_type(op, op["tag"]), "fields": {q["name"]: {"name": go_name(q["name"]), "type": go_type(spec, q["schema"], True)} for q in op["query"]}} if op["query"] else None,
            "java": op["name"],
            "cs": op["name"][:1].upper() + op["name"][1:] + "Async",
            "rb": snake(op["name"]),
        }
    text = json.dumps({"ops": out, "goTypes": go_docs_info(spec)}, indent=2, ensure_ascii=False) + "\n"
    for t in targets:
        t.write_text(text)


def main() -> None:
    if "--fetch" in sys.argv:
        url = sys.argv[sys.argv.index("--fetch") + 1]
        with urllib.request.urlopen(url) as r:  # noqa: S310 (developer-provided URL)
            SPEC_PATH.write_bytes(r.read())
    spec = Spec(json.loads(SPEC_PATH.read_text()))
    gen_ts(spec)
    gen_py(spec)
    gen_php(spec)
    sys.path.insert(0, str(Path(__file__).parent))
    from gen_go import gen_go
    gen_go(spec, ROOT)
    from gen_jvm import gen_csharp, gen_java, gen_ruby
    gen_java(spec, ROOT)
    gen_csharp(spec, ROOT)
    gen_ruby(spec, ROOT)
    from gen_extras import gen_mcp, gen_n8n, gen_postman
    gen_postman(spec, ROOT)
    gen_n8n(spec, ROOT)
    gen_mcp(spec, ROOT)
    targets = [ROOT / "sdk-map.json"]
    if "--web" in sys.argv:
        targets.append(Path(sys.argv[sys.argv.index("--web") + 1]))
    gen_map(spec, targets)
    if "--web" in sys.argv:
        # the docs offer the Postman collection for download from the site
        web_public = Path(sys.argv[sys.argv.index("--web") + 1]).resolve().parents[3] / "public"
        if web_public.is_dir():
            (web_public / "zapz.postman_collection.json").write_text((ROOT / "postman" / "zapz.postman_collection.json").read_text())
    print(f"generated {len(spec.ops)} operations, {len(spec.schemas)} schemas")


if __name__ == "__main__":
    main()
