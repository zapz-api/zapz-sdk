# ----------------------------------------------------------------- helpers

def snake(name: str) -> str:
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return s.lower()


def pascal(name: str) -> str:
    return name[:1].upper() + name[1:]


def ref_name(ref: str) -> str:
    return ref.split("/")[-1]


def inline_empty_schemas(data: dict) -> dict:
    """Entities without described fields (Instance, WebhookSubscription...) become plain objects,
    so the SDKs type them as maps instead of empty classes nobody can read fields from."""
    schemas = data.get("components", {}).get("schemas", {})
    empty = {n for n, sc in schemas.items() if sc.get("type") == "object" and not sc.get("properties")}

    def walk(v):
        if isinstance(v, dict):
            if "$ref" in v and v["$ref"].split("/")[-1] in empty:
                return {"type": "object"}
            return {k: walk(x) for k, x in v.items()}
        if isinstance(v, list):
            return [walk(x) for x in v]
        return v

    data = walk(data)
    for n in empty:
        data["components"]["schemas"].pop(n, None)
    return data


class Spec:
    def __init__(self, data: dict):
        data = inline_empty_schemas(data)
        self.data = data
        self.schemas: dict = data.get("components", {}).get("schemas", {})
        self.ops = self._ops()
        self.request_roots = {op["body_schema"] for op in self.ops if op["body_schema"]}
        self.type_names = {n: self._type_name(n) for n in self.schemas}

    def _type_name(self, schema: str) -> str:
        base = schema[:-3] if schema.endswith("Dto") else schema
        return base + "Params" if schema in self.request_roots else base

    def _ops(self) -> list[dict]:
        ops = []
        for path, item in self.data["paths"].items():
            for method, op in item.items():
                tag = op["tags"][0]
                op_id = op["operationId"]
                params = op.get("parameters", [])
                is_webhook = path.startswith("/v1/webhooks")
                rename = WEBHOOK_PATH_PARAMS if is_webhook else PATH_PARAM_NAMES
                path_params = [
                    {"name": p["name"], "arg": rename.get(p["name"], p["name"])}
                    for p in params if p["in"] == "path"
                ]
                # keep the order in which they appear in the path
                order = re.findall(r"{(\w+)}", path)
                path_params.sort(key=lambda p: order.index(p["name"]))
                query = [
                    {"name": p["name"], "required": p.get("required", False), "schema": p.get("schema", {}), "description": p.get("description", "")}
                    for p in params if p["in"] == "query"
                ]
                body_schema = None
                body_inline = None
                body_required = False
                rb = op.get("requestBody")
                if rb:
                    sch = rb.get("content", {}).get("application/json", {}).get("schema", {})
                    if "$ref" in sch:
                        body_schema = ref_name(sch["$ref"])
                    else:
                        body_inline = sch
                    body_required = rb.get("required", False)
                resp = None
                for code, r in op.get("responses", {}).items():
                    if code.startswith("2"):
                        sch = r.get("content", {}).get("application/json", {}).get("schema")
                        if sch:
                            resp = sch
                        break
                ops.append({
                    "id": op_id,
                    "tag": tag,
                    "resource": RESOURCES[tag],
                    "name": METHODS.get(op_id, op_id),
                    "method": method.upper(),
                    "path": path[len("/v1"):] if path.startswith("/v1") else path,
                    "summary": op.get("summary", ""),
                    "path_params": path_params,
                    "query": query,
                    "body_schema": body_schema,
                    "body_inline": body_inline,
                    "body_required": body_required,
                    "response": resp,
                })
        return ops

    def body(self, op: dict) -> dict | None:
        if op["body_schema"]:
            return self.schemas[op["body_schema"]]
        return op["body_inline"]

    def auto_client_message_id(self, op: dict) -> bool:
        b = self.body(op)
        return bool(b and "clientMessageId" in (b.get("properties") or {}))

    def body_has_required(self, op: dict) -> bool:
        b = self.body(op)
        return bool(b and b.get("required"))


